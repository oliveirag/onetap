// Refreshes src/theme/tokens.json from Gui's design system and writes store-tokens.css
// (CSS variables for Amer's store page) from the same resolver the app uses.
// Run: node --experimental-strip-types scripts/sync-tokens.mjs   (Node 22.6+)
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const src = join(homedir(), 'Developer/design-system/tokens/tokens.json');
const dest = new URL('../src/theme/tokens.json', import.meta.url);

if (existsSync(src)) {
  copyFileSync(src, dest);
} else {
  console.warn(`Design system not found at ${src}. Using the committed snapshot.`);
}

const { resolveTheme } = await import('../src/theme/resolve.ts');
const tokens = JSON.parse(readFileSync(dest, 'utf8'));

let css = ['dark', 'light']
  .map((scheme) => {
    const t = resolveTheme(tokens, scheme);
    const vars = Object.entries(t.color).flatMap(([group, map]) =>
      Object.entries(map).map(([name, value]) => `  --${group}-${name}: ${value};`),
    );
    const selector = scheme === 'dark' ? ':root' : ':root[data-theme="light"]';
    return `${selector} {\n${vars.join('\n')}\n}`;
  })
  .join('\n\n');

// Type, space, radius, sizes and motion for the store page, in the tokens' desktop mode (the laptop).
// Same reference rules as resolve.ts: follow "{a.b}" refs, applying the mode at every hop.
const get = (path) => path.split('.').reduce((node, key) => node?.[key], tokens);
const pick = (token, mode) => token?.$extensions?.modes?.[mode] ?? token?.$value;
const deref = (value, mode) =>
  typeof value === 'string' && value.startsWith('{') && value.endsWith('}') ? deref(pick(get(value.slice(1, -1)), mode), mode) : value;
const desktop = (token) => deref(pick(token, 'desktop'), 'desktop');
const r = tokens.responsive;
const m = tokens.motion;
const named = (group) => Object.entries(group).filter(([k]) => !k.startsWith('$'));

const layout = [
  `  --font-mono: ${tokens.brand.font.family.mono.$value.map((f) => (f.includes(' ') ? `'${f}'` : f)).join(', ')};`,
  ...named(r.type).flatMap(([name, t]) => [
    `  --type-${name}-size: ${desktop(t['font-size'])};`,
    `  --type-${name}-line: ${desktop(t['line-height'])};`,
    `  --type-${name}-weight: ${deref(t['font-weight'].$value)};`,
    `  --type-${name}-tracking: ${t['letter-spacing'].$value};`,
  ]),
  ...named(r.space).map(([name, t]) => `  --space-${name}: ${desktop(t)};`),
  ...named(tokens.alias.radius).map(([name, t]) => `  --radius-${name}: ${deref(t.$value)};`),
  `  --page-margin: ${desktop(r['page-margin'])};`,
  ...named(r['control-height']).map(([name, t]) => `  --control-height-${name}: ${desktop(t)};`),
  `  --hit-target: ${desktop(r['hit-target-min'])};`,
  ...named(m.easing).map(([name, t]) => `  --ease-${name}: cubic-bezier(${t.$value.join(', ')});`),
  ...named(m.duration).map(([name, t]) => `  --duration-${name}: ${t.$value};`),
];
css += `\n\n/* Layout and motion: desktop mode. */\n:root {\n${layout.join('\n')}\n}`;

writeFileSync(new URL('../store-tokens.css', import.meta.url), `/* Generated by scripts/sync-tokens.mjs. Do not edit. */\n${css}\n`);
console.log('tokens synced');
